export function normalizeRoom(roomCode) {
  return String(roomCode || "").toUpperCase().replace(/\s+/g, "");
}

export function getPrompts(roomCode, customCourses = []) {
  const key = normalizeRoom(roomCode);
  const custom = customCourses.find((c) => normalizeRoom(c.code) === key);
  if (custom?.prompts?.length) return custom.prompts;
  if (key === "INT6136E") return PROMPTS_INT6136E;
  if (key === "INT6136P") return PROMPTS_INT6136P;
  if (key === "LAW6003") return PROMPTS_LAW6003;
  if (key === "INT6066") return PROMPTS_INT6066;
  return custom?.prompts || PROMPTS_INT6066;
}

export function getCourseMeta(roomCode, customCourses = []) {
  const key = normalizeRoom(roomCode);
  const builtin = COURSES.find((c) => c.code === key);
  const custom = customCourses.find((c) => normalizeRoom(c.code) === key);
  if (custom || builtin) {
    const instructions = custom?.instructions?.length ? custom.instructions : builtin?.instructions || [];
    return {
      code: key,
      title: custom?.title || builtin?.title || key,
      blurb: custom?.blurb || builtin?.blurb || "",
      introTitle: custom?.intro_title || builtin?.introTitle || "",
      instructions,
      closing: custom?.closing || builtin?.closing || "",
      custom: Boolean(custom) && !builtin
    };
  }
  return {
    code: key,
    title: key,
    blurb: "Custom room"
  };
}
